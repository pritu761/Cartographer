import type { Metadata } from "next";
import "./globals.css";

export const metadata: Metadata = {
  title: "Cartograph — Codebase Dependency Map",
  description: "AST-parsed dependency map and structural intelligence for TypeScript & JavaScript codebases.",
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="en" suppressHydrationWarning>
      <head>
        <script
          dangerouslySetInnerHTML={{
            __html: `
              (function() {
                try {
                  var saved = localStorage.getItem('cartograph_theme');
                  var prefersDark = window.matchMedia('(prefers-color-scheme: dark)').matches;
                  if (saved === 'dark' || (!saved && prefersDark)) {
                    document.documentElement.classList.add('dark');
                  } else {
                    document.documentElement.classList.remove('dark');
                  }
                } catch (e) {}
              })();
            `,
          }}
        />
      </head>
      <body className="antialiased select-none" suppressHydrationWarning>{children}</body>
    </html>
  );
}
